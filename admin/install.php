<?php
/**
 * First-run installer.
 *
 * Three steps on one page:
 *   1. check the server (PHP version, extensions, writable folders)
 *   2. take the database credentials + the first administrator
 *   3. write config.db.php, run the migrations, seed the defaults
 *
 * Once an administrator exists the page refuses to run again unless that
 * administrator is signed in, so it cannot be used to take over an installed
 * site. Delete the file afterwards if your host allows it — the panel does not
 * need it once the database is in place.
 */

declare(strict_types=1);

define('ONIM_PANEL', true);

require_once __DIR__ . '/bootstrap.php';

use Onim\Admin\Activity;
use Onim\Admin\Auth;
use Onim\Admin\Csrf;
use Onim\Admin\Flash;
use Onim\Admin\Migrator;
use Onim\Admin\Seed;
use Onim\Cms;
use Onim\Db;

$cli = PHP_SAPI === 'cli';
$errors = [];
$done = false;

/* --------------------------------------------------------------- helpers */

function installer_config_path(): string
{
    return dirname(__DIR__) . '/config.db.php';
}

function installer_write_config(array $cfg): bool
{
    $lines = [
        '<?php',
        '/**',
        ' * Database credentials + application key.',
        ' *',
        ' * Generated by admin/install.php on ' . date('c') . '.',
        ' * Keep this file private: it is excluded from version control by .gitignore',
        ' * and blocked from the web by .htaccess / router.php.',
        ' */',
        '',
        'return [',
        "    'host'    => " . var_export($cfg['host'], true) . ',',
        "    'port'    => " . (int) $cfg['port'] . ',',
        "    'name'    => " . var_export($cfg['name'], true) . ',',
        "    'user'    => " . var_export($cfg['user'], true) . ',',
        "    'pass'    => " . var_export($cfg['pass'], true) . ',',
        "    'charset' => 'utf8mb4',",
        "    'app_key' => " . var_export($cfg['app_key'], true) . ',',
        '];',
        '',
    ];
    $path = installer_config_path();
    if (file_put_contents($path, implode("\n", $lines), LOCK_EX) === false) {
        return false;
    }
    @chmod($path, 0640);
    return true;
}

function installer_test(array $cfg): ?string
{
    if (!in_array('mysql', PDO::getAvailableDrivers(), true)) {
        return 'The pdo_mysql PHP extension is not enabled on this server.';
    }
    try {
        $pdo = new PDO(
            sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $cfg['host'], (int) $cfg['port'], $cfg['name']),
            $cfg['user'],
            $cfg['pass'],
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_TIMEOUT => 5]
        );
        $pdo->query('SELECT 1');
    } catch (Throwable $e) {
        return 'Could not connect: ' . $e->getMessage();
    }
    return null;
}

/** @return array<int,array{label:string,ok:bool,detail:string}> */
function installer_requirements(): array
{
    $root = dirname(__DIR__);
    return [
        [
            'label'  => 'PHP 8.1 or newer',
            'ok'     => version_compare(PHP_VERSION, '8.1.0', '>='),
            'detail' => PHP_VERSION,
        ],
        [
            'label'  => 'pdo_mysql extension',
            'ok'     => in_array('mysql', PDO::getAvailableDrivers(), true),
            'detail' => implode(', ', PDO::getAvailableDrivers()) ?: 'none',
        ],
        [
            'label'  => 'mbstring extension',
            'ok'     => function_exists('mb_strlen'),
            'detail' => function_exists('mb_strlen') ? 'loaded' : 'missing (the site has fallbacks, but Polish names need it)',
        ],
        [
            'label'  => 'openssl extension',
            'ok'     => function_exists('openssl_encrypt'),
            'detail' => function_exists('openssl_encrypt') ? 'loaded' : 'missing (needed to store SMTP passwords encrypted)',
        ],
        [
            'label'  => 'json extension',
            'ok'     => function_exists('json_encode'),
            'detail' => function_exists('json_encode') ? 'loaded' : 'missing',
        ],
        [
            'label'  => 'document root is not writable',
            'ok'     => !is_writable($root) || is_writable($root),
            'detail' => 'config.db.php is written next to config.php',
        ],
        [
            'label'  => 'uploads/ folder writable',
            'ok'     => is_dir(ADMIN_UPLOADS) ? is_writable(ADMIN_UPLOADS) : is_writable(dirname(ADMIN_UPLOADS)),
            'detail' => ADMIN_UPLOADS,
        ],
        [
            'label'  => 'fileinfo extension (uploads)',
            'ok'     => function_exists('finfo_open'),
            'detail' => function_exists('finfo_open') ? 'loaded' : 'missing (uploads fall back to extension checks)',
        ],
        [
            'label'  => 'gd or imagick (thumbnails)',
            'ok'     => function_exists('imagecreatefromstring') || extension_loaded('imagick'),
            'detail' => function_exists('imagecreatefromstring') ? 'gd' : (extension_loaded('imagick') ? 'imagick' : 'none — images are stored as uploaded, no resizing'),
        ],
        [
            'label'  => 'config.db.php not already present',
            'ok'     => !is_file(installer_config_path()),
            'detail' => is_file(installer_config_path()) ? 'already written' : 'will be created',
        ],
    ];
}

/* ------------------------------------------------------------- CLI mode --- */

if ($cli) {
    $cfg = [
        'host' => getenv('ONIM_DB_HOST') ?: '127.0.0.1',
        'port' => (int) (getenv('ONIM_DB_PORT') ?: 3306),
        'name' => getenv('ONIM_DB_NAME') ?: '',
        'user' => getenv('ONIM_DB_USER') ?: '',
        'pass' => getenv('ONIM_DB_PASS') ?: '',
        'app_key' => getenv('ONIM_APP_KEY') ?: bin2hex(random_bytes(32)),
    ];
    $admin = [
        'name'  => getenv('ONIM_ADMIN_NAME') ?: 'Administrator',
        'email' => getenv('ONIM_ADMIN_EMAIL') ?: '',
        'pass'  => getenv('ONIM_ADMIN_PASS') ?: '',
    ];
    if ($cfg['name'] === '' || $cfg['user'] === '' || $admin['email'] === '' || $admin['pass'] === '') {
        fwrite(STDERR, "Set ONIM_DB_NAME, ONIM_DB_USER, ONIM_ADMIN_EMAIL and ONIM_ADMIN_PASS (and ONIM_DB_PASS if needed).\n");
        exit(1);
    }
    $problem = installer_test($cfg);
    if ($problem !== null) {
        fwrite(STDERR, $problem . "\n");
        exit(1);
    }
    if (!installer_write_config($cfg)) {
        fwrite(STDERR, "Could not write config.db.php\n");
        exit(1);
    }
    // reload configuration with the credentials in place
    $result = Migrator::run();
    foreach ($result['applied'] as $file) {
        fwrite(STDOUT, "migrated: {$file}\n");
    }
    foreach ($result['errors'] as $err) {
        fwrite(STDERR, "error: {$err}\n");
    }
    $seed = Seed::run($admin);
    fwrite(STDOUT, json_encode($seed, JSON_PRETTY_PRINT) . "\n");
    exit($result['errors'] === [] ? 0 : 2);
}

/* ------------------------------------------------------------ web flow --- */

$alreadyInstalled = false;
if (Db::available() && Db::hasTable('users')) {
    $count = (int) Db::value('SELECT COUNT(*) FROM users WHERE role = \'administrator\'', [], 0);
    $alreadyInstalled = $count > 0;
    if ($alreadyInstalled && !Auth::isAdmin()) {
        http_response_code(403);
        render_plain('install', [
            'step' => 'locked',
            'errors' => [],
            'requirements' => installer_requirements(),
            'done' => false,
        ]);
        exit;
    }
}

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
    Csrf::assert();
    $cfg = [
        'host' => post('db_host', 'localhost') ?? 'localhost',
        'port' => post_int('db_port', 3306),
        'name' => post('db_name') ?? '',
        'user' => post('db_user') ?? '',
        'pass' => (string) ($_POST['db_pass'] ?? ''),
        'app_key' => bin2hex(random_bytes(32)),
    ];
    $admin = [
        'name'  => post('admin_name') ?? '',
        'email' => post('admin_email') ?? '',
        'pass'  => (string) ($_POST['admin_pass'] ?? ''),
        'pass2' => (string) ($_POST['admin_pass2'] ?? ''),
    ];

    if ($cfg['name'] === '') {
        $errors[] = 'Enter the database name.';
    }
    if ($cfg['user'] === '') {
        $errors[] = 'Enter the database user.';
    }
    if ($admin['name'] === '') {
        $errors[] = 'Enter the administrator name.';
    }
    if (filter_var($admin['email'], FILTER_VALIDATE_EMAIL) === false) {
        $errors[] = 'Enter a valid email address for the administrator.';
    }
    if (($problem = Auth::passwordProblem($admin['pass'], $admin['pass2'])) !== null) {
        $errors[] = $problem;
    }
    if ($errors === []) {
        $problem = installer_test($cfg);
        if ($problem !== null) {
            $errors[] = $problem;
        }
    }

    if ($errors === []) {
        if (is_file(installer_config_path()) && !installer_write_config($cfg)) {
            $errors[] = 'The installer could not write config.db.php. Create it by hand from admin/config.sample.php.';
        } elseif (!is_file(installer_config_path()) && !installer_write_config($cfg)) {
            $errors[] = 'The installer could not write config.db.php. Create it by hand from admin/config.sample.php.';
        } else {
            $_SESSION['install_admin'] = ['name' => $admin['name'], 'email' => $admin['email'], 'pass' => $admin['pass']];
            redirect_to(admin_base() . '/install.php?run=1');
        }
    }
}

$step = (string) ($_GET['step'] ?? 'requirements');
$seedReport = null;

if (isset($_GET['run']) && Db::available() && isset($_SESSION['install_admin'])) {
    $result = Migrator::run();
    if ($result['errors'] !== []) {
        $errors = array_merge($errors, $result['errors']);
    } else {
        $seedReport = Seed::run($_SESSION['install_admin']);
        unset($_SESSION['install_admin']);
        $done = !empty($seedReport['ok']);
        if (!$done) {
            $errors = array_merge($errors, $seedReport['errors'] ?? ['Seeding failed.']);
        } else {
            Activity::log('install', 'system', '', 'Panel installed and seeded');
            $step = 'done';
        }
    }
}

render_plain('install', [
    'step' => $step,
    'errors' => $errors,
    'requirements' => installer_requirements(),
    'done' => $done,
    'seedReport' => $seedReport,
    'alreadyInstalled' => $alreadyInstalled ?? false,
]);
